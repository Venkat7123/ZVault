-- 06_show_security.sql
-- READ-ONLY. Shows every security rule Bots Bank has inside Db2.
-- Safe to run any time, as DB2INST1 (or SECADM1).

-- 1. Which tables have row rules (R) and/or column masks (C) switched on
SELECT VARCHAR(TABNAME, 12) AS TABLE_NAME, CONTROL AS RULES_ON
FROM SYSCAT.TABLES WHERE TABSCHEMA = 'BANK' ORDER BY TABNAME;

-- 2. The row permissions and column masks themselves
SELECT VARCHAR(CONTROLNAME, 24) AS RULE, CONTROLTYPE AS TYPE,
       VARCHAR(TABNAME, 10) AS ON_TABLE, VARCHAR(COALESCE(COLNAME, '-'), 8) AS ON_COLUMN,
       ENABLE AS ENABLED
FROM SYSCAT.CONTROLS WHERE TABSCHEMA = 'BANK' ORDER BY TABNAME, CONTROLNAME;

-- 3. Who has which bank role
SELECT VARCHAR(ROLENAME, 10) AS ROLE, VARCHAR(GRANTEE, 12) AS EMPLOYEE
FROM SYSCAT.ROLEAUTH WHERE ROLENAME IN ('CLERK', 'MANAGER', 'AUDITOR')
ORDER BY ROLENAME, GRANTEE;

-- 4. Employees and their branch (the row rules read this table)
SELECT VARCHAR(EMP_ID, 10) AS EMP_ID, VARCHAR(ROLE_NAME, 8) AS ROLE,
       COALESCE(BRANCH_ID, 'ALL') AS BRANCH, ACTIVE
FROM BANK.EMPLOYEES ORDER BY EMP_ID;

-- 5. The AI gateway's trusted context: who, from where, may act as whom
SELECT VARCHAR(CONTEXTNAME, 16) AS CONTEXT, VARCHAR(SYSTEMAUTHID, 8) AS GATEWAY, ENABLED
FROM SYSCAT.CONTEXTS;
SELECT VARCHAR(CONTEXTNAME, 16) AS CONTEXT, VARCHAR(ATTR_NAME, 10) AS ATTRIBUTE,
       VARCHAR(ATTR_VALUE, 16) AS VALUE
FROM SYSCAT.CONTEXTATTRIBUTES;
SELECT VARCHAR(SURROGATEAUTHID, 12) AS AI_MAY_ACT_AS, AUTHENTICATE AS NEEDS_PASSWORD
FROM SYSCAT.SURROGATEAUTHIDS WHERE CONTEXT = 'AI_GATEWAY_CTX' ORDER BY 1;

-- 6. Table rights: AIGW should only have INSERT on ACCESS_LOG
SELECT VARCHAR(GRANTEE, 10) AS GRANTEE, GRANTEETYPE AS T, VARCHAR(TABNAME, 12) AS TABLE_NAME,
       SELECTAUTH AS SEL, INSERTAUTH AS INS, UPDATEAUTH AS UPD, DELETEAUTH AS DEL
FROM SYSCAT.TABAUTH WHERE TABSCHEMA = 'BANK' AND GRANTEE <> 'DB2INST1'
ORDER BY TABNAME, GRANTEE;

-- 7. Database-level powers (after hardening, only SECADM1 has SECADM)
SELECT VARCHAR(GRANTEE, 12) AS GRANTEE, SECURITYADMAUTH AS SECADM, DBADMAUTH AS DBADM,
       DATAACCESSAUTH AS DATAACCESS, CONNECTAUTH AS CONNECT
FROM SYSCAT.DBAUTH ORDER BY GRANTEE;

-- 8. Proof: the database admin itself sees no bank data
SELECT COUNT(*) AS ADMIN_SEES_CUSTOMERS FROM BANK.CUSTOMERS;
SELECT COUNT(*) AS ADMIN_SEES_LOANS FROM BANK.LOANS;
