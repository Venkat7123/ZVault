-- 01_bank_schema.sql
-- Fake "Bots Bank": branches, employees, customers, loans, access log.
-- All data is synthetic (generic names, fake Aadhaar/PAN/mobile numbers).

CREATE SCHEMA BANK;

CREATE TABLE BANK.BRANCHES (
  BRANCH_ID   VARCHAR(10) NOT NULL PRIMARY KEY,
  BRANCH_NAME VARCHAR(50) NOT NULL,
  CITY        VARCHAR(30) NOT NULL
);

-- Who works where, and in which role. The security rules read this table.
CREATE TABLE BANK.EMPLOYEES (
  EMP_ID     VARCHAR(30) NOT NULL PRIMARY KEY,   -- must match the Db2 user ID (uppercase)
  FULL_NAME  VARCHAR(60) NOT NULL,
  ROLE_NAME  VARCHAR(20) NOT NULL,
  BRANCH_ID  VARCHAR(10) REFERENCES BANK.BRANCHES (BRANCH_ID),
  ACTIVE     CHAR(1) NOT NULL DEFAULT 'Y'
);

CREATE TABLE BANK.CUSTOMERS (
  CUST_ID    INTEGER       NOT NULL PRIMARY KEY,
  FULL_NAME  VARCHAR(60)   NOT NULL,
  BRANCH_ID  VARCHAR(10)   NOT NULL REFERENCES BANK.BRANCHES (BRANCH_ID),
  BALANCE    DECIMAL(15,2) NOT NULL,
  AADHAAR    CHAR(12)      NOT NULL,
  PAN        CHAR(10)      NOT NULL,
  MOBILE     VARCHAR(15)   NOT NULL
);

CREATE TABLE BANK.LOANS (
  LOAN_ID    INTEGER       NOT NULL PRIMARY KEY,
  CUST_ID    INTEGER       NOT NULL REFERENCES BANK.CUSTOMERS (CUST_ID),
  BRANCH_ID  VARCHAR(10)   NOT NULL REFERENCES BANK.BRANCHES (BRANCH_ID),
  AMOUNT     DECIMAL(15,2) NOT NULL,
  STATUS     VARCHAR(20)   NOT NULL
);

-- Every AI request is recorded here (who asked, what was decided, why).
CREATE TABLE BANK.ACCESS_LOG (
  LOG_ID        BIGINT NOT NULL GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  EVENT_TIME    TIMESTAMP NOT NULL DEFAULT CURRENT TIMESTAMP,
  EMP_ID        VARCHAR(30) NOT NULL,
  ACTION        VARCHAR(30) NOT NULL,
  DECISION      VARCHAR(10) NOT NULL,
  ROWS_RETURNED INTEGER,
  REASON        VARCHAR(500)
);

