-- 02_security.sql
-- The master-key fix inside Db2 itself:
--   * roles (CLERK, MANAGER, AUDITOR)
--   * row permissions: staff see only their own branch, auditors see all
--   * column masks: Aadhaar / PAN / mobile hidden unless the role needs them
-- After this runs, even the Db2 admin (DB2INST1) sees 0 customer rows.

-- ---------- Roles ----------
CREATE ROLE CLERK;
CREATE ROLE MANAGER;
CREATE ROLE AUDITOR;

GRANT ROLE CLERK   TO USER CLERK1;
GRANT ROLE CLERK   TO USER CLERK2;
GRANT ROLE MANAGER TO USER MANAGER1;
GRANT ROLE AUDITOR TO USER AUDITOR1;

GRANT CONNECT ON DATABASE TO ROLE CLERK;
GRANT CONNECT ON DATABASE TO ROLE MANAGER;
GRANT CONNECT ON DATABASE TO ROLE AUDITOR;

-- Read-only access for every role (the AI never writes directly).
GRANT SELECT ON BANK.BRANCHES  TO ROLE CLERK;
GRANT SELECT ON BANK.BRANCHES  TO ROLE MANAGER;
GRANT SELECT ON BANK.BRANCHES  TO ROLE AUDITOR;
GRANT SELECT ON BANK.CUSTOMERS TO ROLE CLERK;
GRANT SELECT ON BANK.CUSTOMERS TO ROLE MANAGER;
GRANT SELECT ON BANK.CUSTOMERS TO ROLE AUDITOR;
GRANT SELECT ON BANK.LOANS     TO ROLE CLERK;
GRANT SELECT ON BANK.LOANS     TO ROLE MANAGER;
GRANT SELECT ON BANK.LOANS     TO ROLE AUDITOR;

-- ---------- Row rules: own branch only (auditors see all) ----------
CREATE PERMISSION BANK.CUSTOMERS_BRANCH_RULE ON BANK.CUSTOMERS
  FOR ROWS WHERE
       VERIFY_ROLE_FOR_USER(SESSION_USER, 'AUDITOR') = 1
    OR ( (   VERIFY_ROLE_FOR_USER(SESSION_USER, 'CLERK')   = 1
          OR VERIFY_ROLE_FOR_USER(SESSION_USER, 'MANAGER') = 1 )
         AND BRANCH_ID IN (SELECT E.BRANCH_ID FROM BANK.EMPLOYEES E
                           WHERE E.EMP_ID = SESSION_USER AND E.ACTIVE = 'Y') )
  ENFORCED FOR ALL ACCESS
  ENABLE;

CREATE PERMISSION BANK.LOANS_BRANCH_RULE ON BANK.LOANS
  FOR ROWS WHERE
       VERIFY_ROLE_FOR_USER(SESSION_USER, 'AUDITOR') = 1
    OR ( (   VERIFY_ROLE_FOR_USER(SESSION_USER, 'CLERK')   = 1
          OR VERIFY_ROLE_FOR_USER(SESSION_USER, 'MANAGER') = 1 )
         AND BRANCH_ID IN (SELECT E.BRANCH_ID FROM BANK.EMPLOYEES E
                           WHERE E.EMP_ID = SESSION_USER AND E.ACTIVE = 'Y') )
  ENFORCED FOR ALL ACCESS
  ENABLE;

-- ---------- Column masks ----------
-- Aadhaar: only auditors see the full number; everyone else sees last 4 digits.
CREATE MASK BANK.AADHAAR_MASK ON BANK.CUSTOMERS FOR COLUMN AADHAAR RETURN
  CASE WHEN VERIFY_ROLE_FOR_USER(SESSION_USER, 'AUDITOR') = 1 THEN AADHAAR
       ELSE 'XXXXXXXX' || SUBSTR(AADHAAR, 9, 4)
  END
  ENABLE;

-- PAN: same rule.
CREATE MASK BANK.PAN_MASK ON BANK.CUSTOMERS FOR COLUMN PAN RETURN
  CASE WHEN VERIFY_ROLE_FOR_USER(SESSION_USER, 'AUDITOR') = 1 THEN PAN
       ELSE 'XXXXXX' || SUBSTR(PAN, 7, 4)
  END
  ENABLE;

-- Mobile: managers and auditors see it; clerks see last 4 digits.
CREATE MASK BANK.MOBILE_MASK ON BANK.CUSTOMERS FOR COLUMN MOBILE RETURN
  CASE WHEN VERIFY_ROLE_FOR_USER(SESSION_USER, 'MANAGER') = 1
         OR VERIFY_ROLE_FOR_USER(SESSION_USER, 'AUDITOR') = 1 THEN MOBILE
       ELSE 'XXXXXX' || RIGHT(MOBILE, 4)
  END
  ENABLE;

-- ---------- Switch the rules on ----------
ALTER TABLE BANK.CUSTOMERS ACTIVATE ROW ACCESS CONTROL ACTIVATE COLUMN ACCESS CONTROL;
ALTER TABLE BANK.LOANS     ACTIVATE ROW ACCESS CONTROL;

-- ---------- Proof ----------
-- DB2INST1 (the admin) has no bank role, so this must return 0.
SELECT COUNT(*) AS ADMIN_SEES_CUSTOMERS FROM BANK.CUSTOMERS;
SELECT COUNT(*) AS ADMIN_SEES_LOANS     FROM BANK.LOANS;
